"""Offline reproducibility gate: regenerate every derived artifact and compare.

The project's reports are meant to be recomputable from the cached Modrinth
responses and the tracked inputs alone. ``chaoslab verify`` runs each generator
inside a scratch root that borrows ``data/`` (mods, modpacks, source),
``candidates.txt``, ``fit_rules.json`` and ``pack_manifest.json``, then compares
the regenerated bytes with the committed files and
``reports/MANIFEST.sha256``.

A mismatch means either the committed report is stale or a generator stopped
being deterministic; both are real failures rather than cosmetic drift.

The gate also validates the *inputs* a report run edits: `candidates.txt` must
still parse and appear in the survey, `PROJECT_PLAN.md` must reference only
report paths, `planned:`-marked report paths (allowed to be absent) and
`chaoslab` subcommands that exist, `pack_manifest.json` must declare a target,
a policy and only candidates that exist, and every cached `.mrpack` must be a
readable zip whose `modrinth.index.json` parses and whose sidecar records the
same byte count. Those checks make the gate applicable to an edit of the inputs
themselves, not only to the derived reports.

``run(..., inputs_only=True)`` skips regeneration and validates only those
inputs, which is the cheap mode a host-level or pre-commit gate can run on every
change; the full mode remains the pre-handoff reproducibility check.
"""

