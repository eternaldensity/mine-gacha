"""Deterministic pack builder: pin builds, write the lock, emit the ``.mrpack``.

The declaration in ``pack_manifest.json`` says which projects ship. This module
decides which *build* of each of them ships, records that decision in
``pack_lock.json``, and renders the result into a Modrinth ``.mrpack``.

Reproducibility is the point: the same manifest plus the same cached Modrinth
responses must yield byte-identical lock, index and archive, so nothing here may
embed a timestamp, a hash-ordered set, or a zip entry mtime. ``chaoslab verify``
checks that by rebuilding in a scratch root and comparing bytes.

A project whose cached response is missing, or whose matching build disappeared,
is a hard error: a pack that quietly loses a mod is worse than a failed build.
"""

from __future__ import annotations

import hashlib
import io
import json
import zipfile
from pathlib import Path

from . import mods
from . import pack as pack_mod
from . import packlint as packlint_mod
from .util import ensure_dir, write_json

LOCK_NAME = "pack_lock.json"
DIST_DIR = "dist"
REPORT_NAME = "reports/pack_build.md"
RULES_NAME = "fit_rules.json"
INDEX_NAME = "modrinth.index.json"
PACK_VERSION = "1.0.0-milestone-a"

# Fixed zip metadata: a container that changes on every run is not a lock.
_ZIP_DATE = (1980, 1, 1, 0, 0, 0)

# The instance needs a deliberate server baseline. Built-in defaults are always
# emitted; a repo ``overrides/`` tree takes precedence and is merged on top.
_BUILTIN_OVERRIDES = {
    "server-overrides/server.properties": (
        "# Generated by `chaoslab build` for milestone A.\n"
        "motd=Chaos Gacha - milestone A\n"
        "online-mode=true\n"
        "view-distance=10\n"
        "simulation-distance=8\n"
        "max-tick-time=-1\n"
        "sync-chunk-writes=false\n"
    ),
}


class BuildError(RuntimeError):
    """A declared project could not be pinned, or the archive could not be rendered."""


def _pick(payload, version: str, loader: str):
    """Select the build ``chaoslab resolve`` would select, for one cached list."""
    matching = [
        entry
        for entry in payload
        if isinstance(entry, dict)
        and version in (entry.get("game_versions") or [])
        and loader in (entry.get("loaders") or [])
    ]
    matching.sort(key=lambda entry: mods._published(entry.get("date_published")), reverse=True)
    releases = [entry for entry in matching if entry.get("version_type") == "release"]
    pool = releases or matching
    return pool[0] if pool else None


def _side(value) -> str:
    if value in ("required", "optional", "unsupported"):
        return value
    return "optional"


def _licence(project) -> str:
    info = project.get("license")
    if isinstance(info, dict):
        return str(info.get("id") or info.get("name") or "")
    if isinstance(info, str):
        return info
    return ""


def _pin(root: Path, slug: str, version: str, loader: str) -> dict:
    """Pin one project to one build from the cache alone."""
    project = mods._load_cached(root, mods._project_rel(slug))
    if not isinstance(project, dict):
        raise BuildError(
            f"{slug}: no cached project response; run "
            f"`chaoslab mods resolve --project {slug}` first"
        )
    resolved = str(project.get("slug") or slug)
    payload = mods._load_cached(root, mods._versions_rel(resolved, version, loader))
    if not isinstance(payload, list):
        raise BuildError(f"{slug}: no cached version list for {version}/{loader}")
    chosen = _pick(payload, version, loader)
    if chosen is None:
        raise BuildError(f"{slug}: no {version}/{loader} build in the cache")
    files = [item for item in (chosen.get("files") or []) if isinstance(item, dict)]
    primary = next((item for item in files if item.get("primary")), None)
    if primary is None and files:
        primary = files[0]
    if not isinstance(primary, dict):
        raise BuildError(f"{slug}: build {chosen.get('version_number')} declares no file")
    hashes = primary.get("hashes")
    if not isinstance(hashes, dict):
        raise BuildError(f"{slug}: build {chosen.get('version_number')} declares no file hashes")
    for key in ("filename", "url", "size"):
        if primary.get(key) in (None, ""):
            raise BuildError(f"{slug}: build {chosen.get('version_number')} has no {key}")
    for key in ("sha1", "sha512"):
        if hashes.get(key) in (None, ""):
            raise BuildError(f"{slug}: build {chosen.get('version_number')} has no {key}")
    return {
        "slug": slug,
        "project_id": project.get("id"),
        "title": project.get("title"),
        "licence": _licence(project),
        "client_side": _side(project.get("client_side")),
        "server_side": _side(project.get("server_side")),
        "version_id": chosen.get("id"),
        "version_number": chosen.get("version_number"),
        "version_type": chosen.get("version_type"),
        "date_published": chosen.get("date_published"),
        "filename": primary["filename"],
        "size": int(primary["size"]),
        "sha1": hashes["sha1"],
        "sha512": hashes["sha512"],
        "url": primary["url"],
        "required": sorted(
            {
                str(dep.get("project_id"))
                for dep in (chosen.get("dependencies") or [])
                if isinstance(dep, dict)
                and dep.get("dependency_type") == "required"
                and dep.get("project_id")
            }
        ),
    }


def _effective_env(projects: dict, declared: set) -> dict:
    """Derive the per-side install flags the launcher must see.

    A Modrinth project record describes that project alone, so a library can read
    ``optional`` (or even ``unsupported``) while another project pinned in this
    pack cannot start without it. Launchers honour ``env`` literally: an
    ``optional`` entry is offered as an optional mod at install time and an
    ``unsupported`` one is not installed at all, which is exactly how required
    libraries went missing from a bootable pack.

    The pack therefore derives ``env`` from its own requirement graph:

    * every declared milestone A project is required on both sides, so an
      explicit include wins over a project's own ``optional`` metadata;
    * an ``optional`` dependency of a required dependent becomes required on that
      side, which is the "Prism offered required libraries as optional" defect;
    * a dependency whose metadata says ``unsupported`` on the client is still
      installed there: the client ships every pinned jar, and NeoForge aborts the
      whole pre-load phase when a dependent's declared dependency is absent;
    * ``unsupported`` on the server is left alone, because a client-only rendering
      or tooltip library must stay out of a dedicated server install.

    ``client_side`` / ``server_side`` keep the raw project metadata so the build
    report can show every promotion and the runtime audit can still flag where the
    metadata and the requirement graph disagree.
    """
    env = {
        slug: {"client": entry["client_side"], "server": entry["server_side"]}
        for slug, entry in projects.items()
    }
    by_id = {
        str(entry["project_id"]): slug
        for slug, entry in projects.items()
        if entry.get("project_id")
    }
    for slug in declared:
        if slug not in env:
            continue
        for side in ("client", "server"):
            if env[slug][side] == "optional":
                env[slug][side] = "required"
    changed = True
    while changed:
        changed = False
        for slug, entry in projects.items():
            for dep in entry.get("required") or []:
                target = by_id.get(str(dep))
                if target is None:
                    continue
                for side in ("client", "server"):
                    if env[slug][side] != "required":
                        continue
                    current = env[target][side]
                    if current == "optional":
                        env[target][side] = "required"
                        changed = True
                    elif current == "unsupported" and side == "client":
                        env[target][side] = "required"
                        changed = True
    # Post-condition, not decoration: the defect this function exists to fix was
    # a required dependency left ``optional``, which Prism then offered as an
    # optional install and refused to load without. A build that reintroduces
    # that state must fail here rather than at the launcher.
    for slug, entry in projects.items():
        for dep in entry.get("required") or []:
            target = by_id.get(str(dep))
            if target is None:
                continue
            for side in ("client", "server"):
                if env[slug][side] == "required" and env[target][side] == "optional":
                    raise BuildError(
                        f"{target} is optional on the {side} side but required by {slug}"
                    )
    return env


def _index_files(projects: dict) -> list:
    """One ``files[]`` entry per pinned project, ordered by filename for stability."""
    rows = []
    for slug in sorted(projects, key=lambda name: projects[name]["filename"]):
        entry = projects[slug]
        rows.append(
            {
                "path": f"mods/{entry['filename']}",
                "hashes": {"sha1": entry["sha1"], "sha512": entry["sha512"]},
                "env": dict(entry["env"]),
                "downloads": [entry["url"]],
                "fileSize": entry["size"],
            }
        )
    return rows


def _index(projects: dict, version: str, loader: str, loader_version: str) -> dict:
    return {
        "formatVersion": 1,
        "game": "minecraft",
        "versionId": PACK_VERSION,
        "name": "Chaos Gacha - Milestone A",
        "summary": (
            "Milestone A of the Chaos Gacha pack: declared content, tech, worldgen "
            "and the quest layer, pinned by chaoslab."
        ),
        "files": _index_files(projects),
        "dependencies": {"minecraft": version, loader: loader_version},
    }


def _overrides(root: Path) -> dict:
    """Built-in overrides plus any repo ``overrides/`` files, as ``{entry: bytes}``."""
    files = {name: content.encode("utf-8") for name, content in _BUILTIN_OVERRIDES.items()}
    source = root / "overrides"
    if source.is_dir():
        for path in sorted(source.rglob("*")):
            if path.is_file() and not path.is_symlink():
                rel = path.relative_to(source).as_posix()
                files[f"overrides/{rel}"] = path.read_bytes()
    return files


def _zip_bytes(index: bytes, overrides: dict) -> bytes:
    """Render a byte-stable ``.mrpack``: sorted entries, fixed timestamps."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(
        buffer, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9
    ) as archive:
        entries = {INDEX_NAME: index, **overrides}
        for name in sorted(entries):
            info = zipfile.ZipInfo(name, date_time=_ZIP_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = (0o644 & 0xFFFF) << 16
            archive.writestr(info, entries[name])
    return buffer.getvalue()


def _row(value) -> str:
    text = "" if value is None else str(value)
    return text.replace("|", "\\|").replace("\n", " ").strip() or "—"


def _write_report(
    path: Path,
    *,
    payload: dict,
    projects: dict,
    by_slug: dict,
    slugs: list,
    overrides: dict,
    version: str,
    loader: str,
    loader_version: str,
    lock_payload: dict,
    mrpack: str,
    mrpack_bytes: int,
    mrpack_sha256: str,
) -> None:
    ensure_dir(path.parent)
    carried = [slug for slug in slugs if by_slug.get(slug, {}).get("milestone") != "A"]
    lines = [
        "# Pack build",
        "",
        f"Result: PASS — {len(projects)} projects pinned for {version} / {loader} "
        f"{loader_version}.",
        "",
        f"Archive: `{mrpack}` ({mrpack_bytes} bytes, sha256 `{mrpack_sha256}`)",
        "",
        f"Index: sha256 `{lock_payload['index_sha256']}`. Lock: `{LOCK_NAME}`.",
        "",
        "Generated by `chaoslab build` from `pack_manifest.json` and the cached "
        "Modrinth responses with no network access. Each row is a milestone A "
        "candidate or a required dependency carried into milestone A; the lock "
        "records the build, sha1, sha512, size and download URL so the archive can "
        "be rebuilt byte-for-byte from cache.",
        "",
        f"Carried transitively: {len(carried)} ({', '.join(sorted(carried)) if carried else 'none'}).",
        "",
        "## Pinned projects",
        "",
        "| Section | Milestone | Project | Version | Side | Licence | sha1 |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for slug in slugs:
        entry = projects[slug]
        declared = by_slug.get(slug, {})
        side = f"client {entry['client_side']}, server {entry['server_side']}"
        lines.append(
            "| "
            + " | ".join(
                [
                    _row(declared.get("section")),
                    _row(declared.get("milestone")),
                    f"`{slug}`",
                    _row(entry["version_number"]),
                    _row(side),
                    _row(entry["licence"]),
                    f"`{str(entry['sha1'])[:12]}`",
                ]
            )
            + " |"
        )
    lines += ["", "## Overrides", ""]
    for name in sorted(overrides):
        lines.append(f"- `{name}`")
    promotions = []
    for slug in slugs:
        entry = projects[slug]
        derived = entry.get("env") or {}
        for side in ("client", "server"):
            raw = entry.get(f"{side}_side")
            if derived.get(side) and derived[side] != raw:
                promotions.append((slug, side, raw, derived[side]))
    lines += ["", "## Environment promotions", ""]
    if promotions:
        lines.append(
            "The index `env` flags are derived from the pack requirement graph, not "
            "copied from per-project Modrinth metadata. Each row below is a project "
            "whose metadata understated what the pack needs; without the promotion a "
            "launcher offers it as optional or skips it entirely and dependents fail "
            "to load."
        )
        lines += ["", "| Project | Side | Metadata | Index |", "| --- | --- | --- | --- |"]
        for slug, side, raw, derived in promotions:
            lines.append(f"| `{slug}` | {side} | {raw} | {derived} |")
    else:
        lines.append("None: every project's metadata already matches the requirement graph.")
    lines += [
        "",
        "## What the lock guarantees, and what it does not",
        "",
        "- Guarantees: every declared milestone A project resolves to one concrete "
        "build, its file is identified by sha1 and sha512, and the archive is a "
        "pure function of the manifest plus the cache.",
        "- Does not guarantee: that the set co-loads. A boot test needs a JVM and "
        "the NeoForge installer, neither of which is available offline here; the "
        "runtime harness records that as an external prerequisite instead of "
        "claiming a smoke test that never ran.",
    ]
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    tmp.replace(path)


def run(
    root,
    *,
    manifest: str = packlint_mod.MANIFEST_NAME,
    lock: str = LOCK_NAME,
    dist: str = DIST_DIR,
    report: str = REPORT_NAME,
    rules: str = RULES_NAME,
    version: str = mods.DEFAULT_VERSION,
    loader: str = mods.DEFAULT_LOADER,
    offline: bool = True,
    refresh: bool = False,
    entries=None,
    walk=None,
) -> dict:
    """Pin the closure, write the lock, and render the archive and report."""
    root = Path(root)
    payload = packlint_mod.load_manifest(root, manifest)
    if entries is None or walk is None:
        rows = pack_mod.run(
            root,
            version=version,
            loader=loader,
            offline=offline,
            refresh=refresh,
            rules=rules,
            report="reports/pack_assessment.md",
        )["rows"]
        entries = packlint_mod.expand(payload, rows)
        walk = packlint_mod.closure(entries)

    by_slug = {entry["slug"]: entry for entry in entries}
    slugs = sorted(
        {entry["slug"] for entry in entries if entry["milestone"] == "A"}
        | set(walk["carried"])
    )
    broken = [slug for slug in slugs if by_slug.get(slug, {}).get("status") != "ok"]
    if broken:
        raise BuildError(
            "milestone A pulls unbuildable projects: " + ", ".join(broken)
        )

    target = payload.get("target") or {}
    loader_version = str(target.get("loader_version") or "")
    if not loader_version:
        raise BuildError(f"{manifest}: target.loader_version is required to pin the loader")

    projects = {slug: _pin(root, slug, version, loader) for slug in slugs}
    declared = {entry["slug"] for entry in entries if entry["milestone"] == "A"}
    for slug, sides in _effective_env(projects, declared).items():
        projects[slug]["env"] = sides
    overrides = _overrides(root)

    index_bytes = (
        json.dumps(
            _index(projects, version, loader, loader_version), sort_keys=True, indent=2
        )
        + "\n"
    ).encode("utf-8")
    lock_payload = {
        "format": 1,
        "pack_version": PACK_VERSION,
        "target": {
            "minecraft": version,
            "loader": loader,
            "loader_version": loader_version,
        },
        "index_sha256": hashlib.sha256(index_bytes).hexdigest(),
        "projects": projects,
    }

    lock_path = root / lock
    write_json(lock_path, lock_payload)

    mrpack_name = f"chaos-gacha-{PACK_VERSION}-{version}-{loader}.mrpack"
    mrpack_path = root / dist / mrpack_name
    ensure_dir(mrpack_path.parent)
    mrpack_bytes = _zip_bytes(index_bytes, overrides)
    mrpack_path.write_bytes(mrpack_bytes)

    report_path = root / report
    _write_report(
        report_path,
        payload=payload,
        projects=projects,
        by_slug=by_slug,
        slugs=slugs,
        overrides=overrides,
        version=version,
        loader=loader,
        loader_version=loader_version,
        lock_payload=lock_payload,
        mrpack=mrpack_path.relative_to(root).as_posix(),
        mrpack_bytes=len(mrpack_bytes),
        mrpack_sha256=hashlib.sha256(mrpack_bytes).hexdigest(),
    )
    return {
        "projects": len(projects),
        "carried": len(walk["carried"]),
        "overrides": len(overrides),
        "lock": lock_path.relative_to(root).as_posix(),
        "mrpack": mrpack_path.relative_to(root).as_posix(),
        "report": report_path.relative_to(root).as_posix(),
        "mrpack_sha256": hashlib.sha256(mrpack_bytes).hexdigest(),
        "index_sha256": lock_payload["index_sha256"],
    }
