def _percentiles(values: list[float]) -> tuple[float, float, float]:
    ordered = sorted(float(value) for value in values)
    if not ordered:
        return (0.0, 0.0, 0.0)
    if len(ordered) == 1:
        return (ordered[0], ordered[0], ordered[0])

    def pick(q: float) -> float:
        position = q * (len(ordered) - 1)
        low = int(position)
        high = min(low + 1, len(ordered) - 1)
        fraction = position - low
        return ordered[low] + (ordered[high] - ordered[low]) * fraction

    return (pick(0.10), pick(0.50), pick(0.90))


def _triple(values: tuple[float, float, float], digits: int) -> str:
    return " / ".join(f"{value:.{digits}f}" for value in values)


def _weights(
    stats: dict[tuple[str, int], dict[str, tuple[float, float, float]]],
    gear_ref: float,
    entries_ref: float,
) -> tuple[dict[str, float], dict[str, float]]:
    gear_values = [
        value / gear_ref for row in stats.values() for value in row["gear"]
    ]
    entry_values = [
        value / entries_ref for row in stats.values() for value in row["entries"]
    ]
    stage_values = [value for row in stats.values() for value in row["stage"]]
    spreads = {
        "gear": max(gear_values) - min(gear_values),
        "entries": max(entry_values) - min(entry_values),
        "stage": max(stage_values) - min(stage_values),
    }
    total = sum(spreads.values())
    if total <= 0:
        raw = {"gear": 1 / 3, "entries": 1 / 3, "stage": 1 / 3}
    else:
        raw = {key: value / total for key, value in spreads.items()}
    weights = {key: round(value, 2) for key, value in raw.items()}
    residual = round(1.0 - sum(weights.values()), 2)
    if residual:
        largest = max(weights, key=lambda key: weights[key])
        weights[largest] = round(weights[largest] + residual, 2)
    return weights, spreads


def _score(
    row: tuple[int, float, float],
    weights: dict[str, float],
    gear_ref: float,
    entries_ref: float,
) -> float:
    owned, gear, stage = row
    value = (
        weights["gear"] * min(1.0, gear / gear_ref)
        + weights["entries"] * min(1.0, owned / entries_ref)
        + weights["stage"] * min(1.0, max(0.0, stage))
    )
    return max(0.0, min(1.0, value))


def power_score_sweep(root: Path) -> str:
    root = Path(root)
    entries = [
        entry
        for entry in read_jsonl(root / "data" / "corpus.jsonl")
        if not entry.get("excluded")
    ]
    if not entries:
        raise FetchError("no parsed corpus; run `chaoslab parse` first")
    pool = simulate_mod._build_pool(entries)
    minimum, average, maximum, flat = simulate_mod.PRESETS[PRESET]

    samples: dict[tuple[str, int], list[tuple[int, float, float]]] = {}
    for profile_index, (profile, per_day) in enumerate(PROFILES):
        for trial in range(TRIALS):
            rng = random.Random(SEED + profile_index * 1000 + trial)
            owned: set[str] = set()
            gear = 0.0
            for day in range(1, DAYS + 1):
                for _ in range(per_day):
                    entry = simulate_mod._draw(
                        pool, rng, minimum, average, maximum, flat
                    )
                    entry_id = str(entry.get("id"))
                    if entry_id in owned:
                        continue
                    owned.add(entry_id)
                    if entry.get("category") == "item":
                        gear += float(entry.get("rarity") or 0.0)
                if day in SNAP_DAYS:
                    samples.setdefault((profile, day), []).append(
                        (len(owned), gear, day / DAYS)
                    )

    stats: dict[tuple[str, int], dict[str, tuple[float, float, float]]] = {}
    for key, rows in samples.items():
        stats[key] = {
            "entries": _percentiles([float(row[0]) for row in rows]),
            "gear": _percentiles([float(row[1]) for row in rows]),
            "stage": _percentiles([float(row[2]) for row in rows]),
        }

    late = ("grinder", SNAP_DAYS[-1])
    gear_ref = stats[late]["gear"][2] or 1.0
    entries_ref = stats[late]["entries"][2] or 1.0
    weights, spreads = _weights(stats, gear_ref, entries_ref)

    score_samples: dict[tuple[str, int], list[float]] = {}
    for key, rows in samples.items():
        score_samples[key] = [
            _score(row, weights, gear_ref, entries_ref) for row in rows
        ]
    score_stats = {
        key: _percentiles(values) for key, values in score_samples.items()
    }

    per_day_of = dict(PROFILES)
    lines = [
        "# Power Score sweep (D3)",
        "",
        "Generated by `chaoslab report` with no network access. The sweep drives the",
        "same roller as `chaoslab simulate --preset gold` over a modelled 28-day arc",
        f"under three ticket-income assumptions, with {TRIALS} independent arcs per",
        "profile at fixed seeds. Percentiles are order statistics over those samples,",
        "not distribution tails. This is a model, not a measurement — see Limits.",
        "",
        "## Assumptions",
        "",
        "| profile | tickets/day | tickets over 28 days |",
        "| --- | --- | --- |",
    ]
    for profile, per_day in PROFILES:
        lines.append(f"| {profile} | {per_day} | {per_day * DAYS} |")

    lines += [
        "",
        "Stage is the fraction of the 28-day arc completed. It is a gate, not a draw,",
        "so it has no variance; replace it with the feat/advancement count once feats",
        "exist (§6.9). Gear totals are the summed rarity of unique item draws: the",
        "corpus has no equipment-stat table, so this is the closest available proxy",
        "for \"gear and attribute totals\".",
        "",
        "## Input distributions",
        "",
        "| profile | snapshot | tickets spent | gear total P10 / P50 / P90 | owned entries P10 / P50 / P90 |",
        "| --- | --- | --- | --- | --- |",
    ]
    for profile, _per_day in PROFILES:
        for day, label in SNAPSHOTS:
            row = stats[(profile, day)]
            lines.append(
                f"| {profile} | {label} | {per_day_of[profile] * day} | "
                f"{_triple(row['gear'], 1)} | {_triple(row['entries'], 0)} |"
            )

    lines += [
        "",
        "## Proposed default weights",
        "",
        "Derived from each input's observed spread across the whole sweep, then",
        "rounded to two decimals and corrected so the vector sums to exactly 1.00.",
        "",
        "| input | observed spread (normalised) | weight |",
        "| --- | --- | --- |",
    ]
    for key in ("gear", "entries", "stage"):
        lines.append(f"| {key} | {spreads[key]:.3f} | {weights[key]:.2f} |")

    lines += [
        "",
        f"- Range: each weight may move ±{WEIGHT_RANGE:.2f}; the vector is then",
        "  re-normalised to 1.00.",
        f"- Weight clamp: each weight is held to [{WEIGHT_FLOOR:.2f}, {WEIGHT_CEILING:.2f}]",
        "  so no single input can dominate or disappear.",
        "- Score clamp: inputs are clamped to 0..1 after normalisation, and the final",
        "  score is clamped to 0..1.",
        f"- Normalisation references: gear = {gear_ref:.1f} rarity, entries = "
        f"{entries_ref:.0f} distinct entries (grinder P90 at late stage).",
        "",
        "## Score curve under the proposed weights",
        "",
        "| profile | early | mid | late |",
        "| --- | --- | --- | --- |",
    ]
    for profile, _per_day in PROFILES:
        cells = [
            _triple(score_stats[(profile, day)], 2)
            for day, _label in SNAPSHOTS
        ]
        lines.append(f"| {profile} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Suggested configuration",
        "",
        "```json",
        "{",
        '  "power_score": {',
        '    "weights": {',
        f'      "gear": {weights["gear"]:.2f},',
        f'      "entries": {weights["entries"]:.2f},',
        f'      "stage": {weights["stage"]:.2f}',
        "    },",
        f'    "weight_range": {WEIGHT_RANGE:.2f},',
        '    "weight_bounds": [0.05, 0.80],',
        f'    "reference": {{"gear": {gear_ref:.1f}, "entries": {entries_ref:.0f}}},',
        '    "score_clamp": [0.0, 1.0]',
        "  }",
        "}",
        "```",
        "",
        "## D3 answer sheet",
        "",
        "```",
        f"weights: gear={weights['gear']:.2f} entries={weights['entries']:.2f} stage={weights['stage']:.2f}",
        f"range: ±{WEIGHT_RANGE:.2f}",
        f"weights clamp: {WEIGHT_FLOOR:.2f} .. {WEIGHT_CEILING:.2f}",
        "score clamp: 0.0 .. 1.0",
        f"reference: gear={gear_ref:.1f} entries={entries_ref:.0f}",
        "```",
        "",
        "Status: answered 2026-11-03 — these values are the shipped default",
        "(`mod/config/power_score.json`); see `DECISIONS.md` D3.",
        "",
        "## Limits",
        "",
        "- Gear is item-rarity, because the corpus carries no equipment stats. A real",
        "  gear/attribute total needs the modded equipment tables.",
        "- Duplicates count once and are not converted to Residue, so long arcs",
        "  understate the value actually spent.",
        "- Only the gold preset is swept; per-band presets and Wild tickets are not.",
        f"- {TRIALS} arcs per profile: P10/P90 are order statistics with visible",
        "  granularity, not tails.",
        "- Ticket income is exogenous. It does not model drops from loot injection,",
        "  conversion, or trading.",
        "",
    ]
    return "\n".join(lines)
