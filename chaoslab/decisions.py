def _matches(text: str, keyword: str) -> bool:
    """Prefix match on a word start; phrases match literally."""
    if " " in keyword:
        return keyword in text
    return re.search(r"(?<![a-z])" + re.escape(keyword), text) is not None


def _classify(description: str) -> tuple[str, str, str, list[str]]:
    """Return (hook, feasibility, confidence, matched keywords) for one curse."""
    text = (description or "").lower()
    for hook, feasibility, keywords in _CURSE_RULES:
        hits = [keyword for keyword in keywords if _matches(text, keyword)]
        if not hits:
            continue
        if hook == "drop":
            confidence = "high"
        elif hook in _IMPLEMENTATION:
            confidence = "high" if len(hits) >= 2 else "medium"
        else:
            confidence = "low"
        return hook, feasibility, confidence, hits
    return "rework", "rework", "low", []


def _cell(value: object) -> str:
    return str(value).replace("|", "/") or "—"


def curse_triage(curses: list[dict]) -> str:
    rows: list[dict] = []
    for curse in sorted(curses, key=lambda row: str(row.get("id"))):
        hook, feasibility, confidence, hits = _classify(curse.get("description", ""))
        label = str(curse.get("label") or "")
        decided = _DECIDED.get(str(curse.get("id")))
        if decided:
            hook = decided["hook"]
            feasibility = decided["feasibility"]
            confidence = "decided"
            hits = []
            note = decided["note"]
        elif hook in _IMPLEMENTATION:
            note = _IMPLEMENTATION[hook]
        else:
            note = _REWORK[hook].format(label=label)
        rows.append(
            {
                "id": str(curse.get("id")),
                "label": label,
                "severity": int(curse.get("severity") or 0),
                "tier": str(curse.get("tier") or ""),
                "hook": hook,
                "feasibility": feasibility,
                "confidence": confidence,
                "matched": ", ".join(hits[:3]) if hits else "",
                "note": note,
                "mature": bool(curse.get("nsfw")),
                "decided": bool(decided),
            }
        )

    tier_counts = Counter(row["tier"] for row in rows)
    hook_counts = Counter(row["hook"] for row in rows)
    feasibility_counts = Counter(row["feasibility"] for row in rows)
    unmatched = sum(1 for row in rows if not row["matched"] and not row["decided"])
    mature = sum(1 for row in rows if row["mature"])
    gated = sum(1 for row in rows if row["mature"] and not row["decided"])

